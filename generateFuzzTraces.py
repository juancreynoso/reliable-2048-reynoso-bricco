"""
Daikon traces of fuzzed games: plays fuzzed games of MainCLI under Chicory,
one .dtrace.gz file per game (Assignment 4, Phase 3.3; extended after the
professor's feedback).

Half of the games start from a random board and half from a board generated by
the grammar of Assignment 5 (boardFuzzer.py), so the trace also contains large
tiles and boards that a short random game never reaches.

Usage: python3 generateFuzzTraces.py [games] [out_dir]
"""

import os
import random
import subprocess
import sys

from boardFuzzer import random_board
from fuzzer import RandomFuzzer

SEED = 42
MIN_MOVES, MAX_MOVES = 50, 1000

CHICORY = [
    "java", "-cp", "lib/daikon.jar:target/classes", "daikon.Chicory",
    "--ppt-select-pattern=ar.edu.unrc.game2048.Board|ar.edu.unrc.game2048.Cell",
]


def main():
    games = int(sys.argv[1]) if len(sys.argv) > 1 else 40
    out_dir = sys.argv[2] if len(sys.argv) > 2 else "daikon-traces/seeded/fuzzer"
    random.seed(SEED)
    os.makedirs(out_dir, exist_ok=True)
    moves = RandomFuzzer(min_length=MIN_MOVES, max_length=MAX_MOVES)

    for i in range(games):
        board = [random_board()] if i % 2 else []
        # -Dseed makes MainCLI place the same random tiles on every run; -ea runs the
        # assert repOk() postconditions, so repOk() is also in the trace
        env = dict(os.environ, JAVA_TOOL_OPTIONS=f"-ea -Dseed={SEED + i}")
        result = subprocess.run(
            CHICORY + [f"--output-dir={out_dir}", f"--dtrace-file=MainCLI-{i:03d}.dtrace.gz",
                       "ar.edu.unrc.game2048.MainCLI"] + board,
            input=moves.fuzz(), capture_output=True, text=True, env=env,
        )
        score = result.stdout.rsplit("Final score:", 1)[-1].strip() or "?"
        status = "OK" if result.returncode == 0 else f"exit {result.returncode}"
        print(f"game {i:03d}: {status}, final score {score}")


if __name__ == "__main__":
    main()
