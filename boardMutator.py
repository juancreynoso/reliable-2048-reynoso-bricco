"""
Assignment 5, Exercise 1b: mutation-based fuzzer for invalid initial boards.

Takes the valid boards generated by the grammar fuzzer (boardFuzzer.py) and
applies 1 to 3 random mutations to each one: insert, replace or delete a
character. 
"""

import random
import subprocess
import sys
from collections import Counter
from concurrent.futures import ThreadPoolExecutor

from boardFuzzer import BOARD_GRAMMAR, COMMAND, SMALL_TILES, LARGE_TILES, TIMEOUT, \
    GrammarFuzzer, run_board
from fuzzer import PASS, FAIL, UNRESOLVED

# Mutator

BOARD_ALPHABET = "0123456789,[]"


def random_character():
    """Half the time a character of the board format, otherwise any printable one."""
    if random.random() < 0.5:
        return random.choice(BOARD_ALPHABET)
    return chr(random.randrange(32, 127))


def insert_random_character(s):
    pos = random.randint(0, len(s))
    return s[:pos] + random_character() + s[pos:]


def replace_random_character(s):
    if not s:
        return s
    pos = random.randrange(len(s))
    return s[:pos] + random_character() + s[pos + 1:]


def delete_random_character(s):
    if not s:
        return s
    pos = random.randrange(len(s))
    return s[:pos] + s[pos + 1:]


MUTATORS = [insert_random_character, replace_random_character, delete_random_character]


def mutate(s, max_mutations=3):
    for _ in range(random.randint(1, max_mutations)):
        s = random.choice(MUTATORS)(s)
    return s


# Oracle and harness

VALID_TILES = {"0"} | set(SMALL_TILES) | set(LARGE_TILES)


def is_valid_board(s):
    """True iff `s` is in the language of BOARD_GRAMMAR."""
    if not (s.startswith("[") and s.endswith("]")):
        return False
    values = s[1:-1].split(",")
    return len(values) == 16 and all(v in VALID_TILES for v in values)


def run_invalid_board(board):
    """Run MainCLI on an invalid board; it must reject it without crashing."""
    try:
        result = subprocess.run(COMMAND + [board], input="q\n",
                                capture_output=True, text=True, timeout=TIMEOUT)
    except subprocess.TimeoutExpired:
        return UNRESOLVED, "timeout"

    if result.returncode == 0:
        return FAIL, "accepted an invalid board"
    if "Exception in thread" in result.stderr or "\tat " in result.stderr:
        exception = next((l.split(": ")[0].split()[-1] for l in result.stderr.splitlines()
                          if "Exception in thread" in l), "unknown")
        return FAIL, f"crashed with {exception}"
    return PASS, ""


def check(board):
    if is_valid_board(board):
        outcome, reason = run_board(board, "q\n")
        return outcome, reason and f"valid board: {reason}"
    return run_invalid_board(board)


def main():
    trials = int(sys.argv[1]) if len(sys.argv) > 1 else 2000
    random.seed(42)
    boards = GrammarFuzzer(BOARD_GRAMMAR)
    inputs = [mutate(boards.fuzz()) for _ in range(trials)]
    still_valid = sum(is_valid_board(b) for b in inputs)

    with ThreadPoolExecutor() as pool:
        results = list(pool.map(check, inputs))

    outcomes = Counter(outcome for outcome, _ in results)
    print(f"{trials} mutated boards ({still_valid} still valid): "
          + ", ".join(f"{k} {outcomes[k]}" for k in (PASS, FAIL, UNRESOLVED)))

    failures = Counter(reason for outcome, reason in results if outcome != PASS)
    for reason, count in failures.most_common():
        examples = [b for b, (o, r) in zip(inputs, results) if r == reason][:2]
        print(f"\n[{count}x] {reason}")
        for example in examples:
            print(f"  e.g. {example}")


if __name__ == "__main__":
    main()
